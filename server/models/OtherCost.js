const mongoose = require("mongoose");

const OtherCostSchema = new mongoose.Schema(
  {
    // =====================================================
    // MÃ CHI PHÍ
    // CP.8.2026.0001
    // =====================================================
    costCode: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },

    // =====================================================
    // MÃ SỐ THUẾ
    // =====================================================
    taxCode: {
      type: String,
      default: "",
      trim: true,
    },

    // =====================================================
    // ĐƠN VỊ NHÀ CUNG CẤP
    // =====================================================
    supplier: {
      type: String,
      required: true,
      trim: true,
    },

    // =====================================================
    // NGÀY PHÁT SINH
    // =====================================================
    costDate: {
      type: Date,
      required: true,
    },

    // =====================================================
    // CHI TIẾT CHI PHÍ
    // =====================================================
    costDetails: {
      type: String,
      default: "",
      trim: true,
    },

    // =====================================================
    // THÀNH TIỀN
    // =====================================================
    totalAmount: {
      type: Number,
      default: 0,
    },

    // =====================================================
    // VAT (%)
    // =====================================================
    vat: {
      type: Number,
      default: 0,
    },

    // =====================================================
    // TỔNG CỘNG
    // =====================================================
    grandTotal: {
      type: Number,
      default: 0,
    },

    // =====================================================
    // GHI CHÚ
    // =====================================================
    note: {
      type: String,
      default: "",
      trim: true,
    },

    // =====================================================
    // SỐ HÓA ĐƠN
    // =====================================================
    invoiceNumber: {
      type: String,
      default: "",
      trim: true,
    },

    // =====================================================
    // NGƯỜI PHỤ TRÁCH
    // =====================================================
    personInCharge: {
      type: String,
      default: "",
      trim: true,
    },

    // =====================================================
    // PHIẾU CHI SỐ
    // =====================================================
    paymentVoucherNumber: {
      type: String,
      default: "",
      trim: true,
    },

    // =====================================================
    // NGÀY THANH TOÁN
    // =====================================================
    paymentDate: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  },
);

const OtherCost = mongoose.model("OtherCost", OtherCostSchema);

module.exports = OtherCost;
